Stream<PositionFix> _denied() => herPositionStream(
      isServiceEnabled: () async => true,
      checkPermission: () async => LocationPermission.denied,
      requestPermission: () async => LocationPermission.denied,
    );

Stream<PositionFix> _deniedForever() => herPositionStream(
      isServiceEnabled: () async => true,
      checkPermission: () async => LocationPermission.deniedForever,
    );

Stream<PositionFix> _servicesOff() =>
    herPositionStream(isServiceEnabled: () async => false);

Future<void> _pumpMap(WidgetTester tester,
    {required bool refused,
    required bool lost,
    Locale locale = const Locale('ja')}) async {
  await tester.pumpWidget(MaterialApp(
    locale: locale,
    localizationsDelegates: const [
      AppL10n.delegate,
      GlobalMaterialLocalizations.delegate,
      GlobalWidgetsLocalizations.delegate,
      GlobalCupertinoLocalizations.delegate,
    ],
    supportedLocales: AppL10n.supportedLocales,
    home: Scaffold(
      body: Align(
        alignment: Alignment.topLeft,
        child: SizedBox(
          width: 361,
          child: AkitaMap(
            height: 320,
            baseTileProvider: _BlankTileProvider(),
            positionRefused: refused,
            positionLost: lost,
            positionDegraded: lost,
          ),
        ),
      ),
    ),
  ));
  await tester.pump();
}

void main() {
  group('the class: typed, her answer only', () {
    test('denied, and denied for good, read from the real position stream',
        () async {
      final denied = await _denied().first;
      final forever = await _deniedForever().first;
      expect(isLocationRefusal(denied), isTrue);
      expect(isPermanentLocationRefusal(denied), isFalse);
      expect(isLocationRefusal(forever), isTrue);
      expect(isPermanentLocationRefusal(forever), isTrue);
    });

    test('location services off is not in the class', () async {
      final off = await _servicesOff().first;
      expect(off, isA<PositionUnavailable>(), reason: 'control');
      expect(isLocationRefusal(off), isFalse);
    });

    test(
        'free text is never read: an unavailability whose reason merely SAYS '
        '"Location permission denied" is not a refusal', () {
      const spoofed = PositionUnavailable('Location permission denied');
      const spoofedForever = PositionUnavailable(
          'Location permission permanently denied — change in OS settings');
      const streamError =
          PositionUnavailable('GPS stream error: Location permission denied');
      expect(isLocationRefusal(spoofed), isFalse);
      expect(isLocationRefusal(spoofedForever), isFalse);
      expect(isLocationRefusal(streamError), isFalse);
    });
  });

  group('the map pill', () {
    testWidgets(
        'refused and NOT lost: 位置情報オフ at the top (a refusal does not '
        'reach the drive brain, so lost is never set)', (tester) async {
      await _pumpMap(tester, refused: true, lost: false);
      final pill = find.byKey(_offKey);
      expect(pill, findsOneWidget);
      expect(find.descendant(of: pill, matching: find.text(_mapJa)),
          findsOneWidget);
      final map = tester.getRect(find.byType(AkitaMap));
      expect(tester.getRect(pill).top - map.top, lessThanOrEqualTo(16));
      expect(find.byKey(_unknownKey), findsNothing);
    });

    testWidgets('refused and lost: still 位置情報オフ, not 現在地不明',
        (tester) async {
      await _pumpMap(tester, refused: true, lost: true);
      expect(find.byKey(_offKey), findsOneWidget);
      expect(find.byKey(_unknownKey), findsNothing);
    });

    testWidgets('English: "No location access"', (tester) async {
      await _pumpMap(tester,
          refused: true, lost: false, locale: const Locale('en'));
      expect(
          find.descendant(of: find.byKey(_offKey), matching: find.text(_mapEn)),
          findsOneWidget);
    });

    testWidgets('lost and not refused: 現在地不明, unchanged', (tester) async {
      await _pumpMap(tester, refused: false, lost: true);
      expect(find.byKey(_unknownKey), findsOneWidget);
      expect(find.byKey(_offKey), findsNothing);
    });

    testWidgets('no icon and no button inside it', (tester) async {
      await _pumpMap(tester, refused: true, lost: false);
      final pill = find.byKey(_offKey);
      expect(pill, findsOneWidget);
      expect(find.descendant(of: pill, matching: find.byType(Icon)),
          findsNothing);
      expect(
          find.descendant(
              of: pill, matching: find.byWidgetPredicate((w) => w is ButtonStyleButton)),
          findsNothing);
      expect(
          find.descendant(
              of: pill, matching: find.byWidgetPredicate((w) => w is GestureDetector)),
          findsNothing);
    });

    testWidgets('a screen reader hears it once: exactly one live region',
        (tester) async {
      final handle = tester.ensureSemantics();
      await _pumpMap(tester, refused: true, lost: false);
      expect(_liveRegionsSaying(tester, _mapJa), 1);
      handle.dispose();
    });
  });

  group('in the real app', () {
    Future<FakeAlertActuators> share(WidgetTester tester,
        Stream<PositionFix> Function() source,
        {Locale locale = const Locale('ja')}) async {
      final actuators = FakeAlertActuators();
      await tester.pumpWidget(const SizedBox.shrink());
      await tester.pump();
      await tester.pumpWidget(SngnavApp(
      // Not about the consent act; that is guarded in
      // test/widgets/location_consent_act_and_privacy_surface_test.dart.
      locationConsent: true,

        actuators: actuators,
        locale: locale,
        clock: DateTime.now,
        jmaFetch: () async => JmaSuccess(_clearObs()),
        positionSource: source,
      ));
      await tester.pump();
      await tester.pump();
      final button = find.byKey(const Key('share-location-button'));
      await tester.ensureVisible(button);
      await tester.pump();
      await tester.tap(button);
      await tester.pump();
      await tester.pump();
      await tester.pump();
      return actuators;
    }

    String? status(WidgetTester tester) {
      final f = find.byKey(_statusKey);
      return f.evaluate().isEmpty ? null : tester.widget<Text>(f).data;
    }

    for (final (name, source, locale, map, line) in [
      ('denied, Japanese', _denied, const Locale('ja'), _mapJa, _deniedJa),
      ('denied, English', _denied, const Locale('en'), _mapEn, _deniedEn),
      ('denied for good, Japanese', _deniedForever, const Locale('ja'), _mapJa,
          _foreverJa),
      ('denied for good, English', _deniedForever, const Locale('en'), _mapEn,
          _foreverEn),
    ]) {
      testWidgets('$name: the pill and the decided line, byte-exact',
          (tester) async {
        await share(tester, source, locale: locale);
        expect(
            find.descendant(of: find.byKey(_offKey), matching: find.text(map)),
            findsOneWidget);
        expect(find.byKey(_unknownKey), findsNothing);
        expect(status(tester), line);
        expect(status(tester)!.startsWith('$map — '), isTrue,
            reason: 'the head of the line is the same bytes as the pill');
      });
    }

    testWidgets('location services off: 現在地不明 and its line, unchanged',
        (tester) async {
      await share(tester, _servicesOff);
      expect(find.byKey(_unknownKey), findsOneWidget);
      expect(find.byKey(_offKey), findsNothing);
      expect(status(tester),
          'GPS を取得できません — 位置情報サービスが無効です。地図は表示されたままです。ルート欄はタップで引き続き使えます。');
    });

    testWidgets(
        'after a denial the row offers 閉じる / "Close", not 停止 / "Stop"; '
        'in a sharing session it still offers 停止', (tester) async {
      await share(tester, _denied);
      expect(find.text('閉じる'), findsOneWidget);
      expect(find.text('停止'), findsNothing,
          reason: 'no Stop for a session that never started');

      await share(tester, _denied, locale: const Locale('en'));
      expect(find.text('Close'), findsOneWidget);
      expect(find.text('Stop'), findsNothing);

      await share(tester, _servicesOff);
      expect(find.text('停止'), findsOneWidget,
          reason: 'control: location services off is not a denial');
      expect(find.text('閉じる'), findsNothing);
    });

    testWidgets('it clears on 閉じる, and on a re-share', (tester) async {
      var answer = LocationPermission.denied;
      await share(
          tester,
          () => herPositionStream(
                isServiceEnabled: () async => true,
                checkPermission: () async => answer,
                requestPermission: () async => answer,
                positionStream: () => const Stream<Position>.empty(),
              ));
      expect(find.byKey(_offKey), findsOneWidget, reason: 'control');

      await tester.ensureVisible(find.text('閉じる'));
      await tester.pump();
      await tester.tap(find.text('閉じる'));
      await tester.pump();
      expect(find.byKey(_offKey), findsNothing, reason: 'cleared on 閉じる');
      expect(find.byKey(const Key('share-location-button')), findsOneWidget,
          reason: 'the same action as 停止: sharing has ended');

      // She allows location this time; before any fix arrives, the words
      // from her previous answer must already be gone.
      answer = LocationPermission.whileInUse;
      final button = find.byKey(const Key('share-location-button'));
      await tester.ensureVisible(button);
      await tester.pump();
      await tester.tap(button);
      await tester.pump();
      expect(find.byKey(_offKey), findsNothing, reason: 'cleared on re-share');
    });
  });
}
