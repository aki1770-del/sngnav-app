/// After her "no" to location, the map says 位置情報オフ, not 現在地不明.
///
/// WHY, written before the act. Ruled 2026-09-13 on the refusal surface: a
/// permission result is the platform's exact answer, so it gets its own words.
/// What matters to her is that location is off for this app and will not come
/// back by itself, and her decision is shown as a setting, not as a machine
/// fault. The words describe the setting and never say that she refused:
/// Android can deny without her taking any action.
///
/// Pinned here, as decided:
/// * the class is her answer only: permission denied, and denied for good.
///   Location services off stays on 現在地不明;
/// * the class is TYPED, never read from free text: a reason string can carry
///   exception text, and matching into it could silence a real failure;
/// * map: the same top-centre pill, key `her-location-off-label`, in the
///   refusal branch, which must not require `positionLost`;
/// * the line under the map: the decided strings, byte-exact, whose head is the
///   same bytes as the pill; only a permanent denial gets the settings hint;
/// * no icon, no button; a screen reader hears it once, as one live region;
/// * it clears on 停止 and on re-share.
