class _BlankTileProvider extends TileProvider {
  @override
  ImageProvider getImage(TileCoordinates coordinates, TileLayer options) =>
      MemoryImage(_blankTile);
}

/// Semantics nodes, anywhere in the tree, that are live regions and whose
/// label carries [text].
int _liveRegionsSaying(WidgetTester tester, String text) {
  var node = tester.getSemantics(find.byType(Scaffold));
  while (node.parent != null) {
    node = node.parent!;
  }
  var n = 0;
  void visit(SemanticsNode node) {
    final data = node.getSemanticsData();
    if (data.flagsCollection.isLiveRegion && data.label.contains(text)) n++;
    node.visitChildren((child) {
      visit(child);
      return true;
    });
  }

  visit(node);
  return n;
}

JmaObservation _clearObs() => JmaObservation(
      stationId: '32402',
      stationName: '秋田',
      temperatureCelsius: 15.0,
      humidityPercent: 30,
      windMetersPerSecond: 1.0,
      snowDepthCm: null,
